<template>
    <div>
        <div v-if="loading" class="card mb-4">
            <div class="card-body text-center py-5">
                <span class="spinner-border text-primary" role="status"></span>
                <p class="text-secondary mt-3 mb-0">Loading email templates…</p>
            </div>
        </div>

        <div v-else-if="error && !templates.length" class="alert alert-danger">
            <i class="bi bi-exclamation-triangle me-1"></i>{{ error }}
        </div>

        <div v-else class="row g-4">
            <div class="col-lg-3">
                <div class="card">
                    <div class="card-header">
                        <h3 class="card-title mb-0">Transactional emails</h3>
                    </div>

                    <div class="list-group list-group-flush">
                        <button
                            v-for="template in templates"
                            :key="template.key"
                            type="button"
                            class="list-group-item list-group-item-action d-flex align-items-center gap-2"
                            :class="{ active: template.key === activeKey }"
                            @click="selectTemplate(template.key)"
                        >
                            <i class="bi bi-envelope mt-1"></i>
                            <span class="flex-grow-1 text-start">
                                <span class="d-block fw-semibold">{{ template.label }}</span>
                                <small :class="template.key === activeKey ? 'text-white-50' : 'text-secondary'">
                                    {{ template.overridden ? 'Custom wording' : 'Built-in wording' }}
                                </small>
                            </span>
                            <i
                                v-if="isDirty(template)"
                                class="bi bi-circle-fill text-warning"
                                style="font-size: 0.5rem"
                                title="Unsaved changes"
                            ></i>
                        </button>
                    </div>
                </div>

                <div class="card mt-3">
                    <div class="card-body small text-secondary">
                        <p class="mb-2"><i class="bi bi-info-circle me-1"></i>How this works</p>
                        <ul class="mb-0 ps-3">
                            <li>Leave a field <strong>blank</strong> to keep the built-in wording.</li>
                            <li>Insert variables like <code>{name}</code> anywhere — see the chips below each field.</li>
                            <li>Links and tokens (reset URLs, order buttons) stay generated by the system.</li>
                            <li>Use <strong>Send test</strong> to receive a real sample before it goes live.</li>
                        </ul>
                    </div>
                </div>
            </div>

            <div class="col-lg-9">
                <div v-if="active" class="card">
                    <div class="card-header d-flex flex-wrap align-items-center gap-3">
                        <div class="me-auto">
                            <h3 class="card-title mb-0">{{ active.label }}</h3>
                            <small class="text-secondary">{{ active.description }}</small>
                        </div>
                        <span class="badge" :class="active.overridden ? 'text-bg-primary' : 'text-bg-secondary'">
                            {{ active.overridden ? 'Customised' : 'Built-in wording' }}
                        </span>
                        <button
                            v-if="active.overridden"
                            type="button"
                            class="btn btn-sm btn-outline-danger"
                            :disabled="saving"
                            @click="revert"
                        >
                            <i class="bi bi-arrow-counterclockwise me-1"></i>Revert to built-in
                        </button>
                    </div>

                    <div class="card-body">
                        <div v-if="error" class="alert alert-danger py-2">
                            <i class="bi bi-exclamation-triangle me-1"></i>{{ error }}
                        </div>

                        <div v-for="field in editableFields" :key="field.name" class="mb-3">
                            <label class="form-label text-uppercase small fw-semibold" :for="`tpl-${field.name}`">
                                {{ field.label }}
                            </label>
                            <textarea
                                v-if="field.type === 'textarea'"
                                :id="`tpl-${field.name}`"
                                v-model="form[field.name]"
                                class="form-control font-monospace"
                                rows="7"
                                :placeholder="defaultBodyText"
                                @focus="lastFocused = `tpl-${field.name}`"
                            ></textarea>
                            <input
                                v-else
                                :id="`tpl-${field.name}`"
                                v-model="form[field.name]"
                                type="text"
                                class="form-control"
                                maxlength="255"
                                :placeholder="String(field.default ?? '')"
                                @focus="lastFocused = `tpl-${field.name}`"
                            />
                            <small v-if="field.variables.length" class="d-flex flex-wrap gap-1 mt-2">
                                <button
                                    v-for="variable in field.variables"
                                    :key="variable.name"
                                    type="button"
                                    class="btn btn-sm btn-outline-secondary py-0 px-2 small"
                                    :title="`${variable.label} — sample: ${variable.sample}`"
                                    @click="insertVariable(variable)"
                                >
                                    {{ '{' + variable.name + '}' }}
                                </button>
                            </small>
                        </div>

                        <div class="row g-3 align-items-end mb-4">
                            <div class="col-md-8">
                                <label class="form-label text-uppercase small fw-semibold" for="tpl-test-email">Send test to</label>
                                <input id="tpl-test-email" v-model="testEmail" type="email" class="form-control" placeholder="you@example.com" />
                            </div>
                            <div class="col-md-4">
                                <button type="button" class="btn btn-outline-primary w-100" :disabled="testing || !testEmail" @click="sendTest">
                                    <span v-if="testing" class="spinner-border spinner-border-sm me-1"></span>
                                    <i v-else class="bi bi-send me-1"></i>
                                    {{ testing ? 'Sending…' : 'Send test email' }}
                                </button>
                            </div>
                        </div>

                        <h4 class="h6 text-uppercase text-secondary">Live preview</h4>
                        <div class="email-preview border rounded p-3 bg-white">
                            <p class="small text-secondary mb-1"><span class="fw-semibold">From:</span> {{ senderLabel }}</p>
                            <p class="fw-semibold mb-2"><span class="text-secondary">Subject:</span> {{ livePreview.subject }}</p>
                            <p v-if="livePreview.greeting" class="fw-semibold mb-2">{{ livePreview.greeting }}</p>
                            <div class="mb-3" style="white-space: pre-line">{{ livePreview.body }}</div>
                            <p v-if="livePreview.actionLabel" class="mb-2">
                                <span class="btn btn-primary btn-sm disabled">{{ livePreview.actionLabel }}</span>
                            </p>
                            <p v-if="livePreview.salutation" class="text-secondary small mb-0">{{ livePreview.salutation }}</p>
                        </div>
                    </div>

                    <div class="card-footer sticky-save d-flex flex-wrap align-items-center gap-3">
                        <span v-if="isDirty(active)" class="text-warning fw-semibold">
                            <i class="bi bi-exclamation-circle me-1"></i>Unsaved changes
                        </span>
                        <span v-else class="text-secondary small">{{ active.overridden ? 'Custom wording is live.' : 'Using the built-in wording.' }}</span>

                        <button type="button" class="btn btn-primary ms-auto" :disabled="saving" @click="save">
                            <span v-if="saving" class="spinner-border spinner-border-sm me-1"></span>
                            <i v-else class="bi bi-check2-circle me-1"></i>
                            Save template
                        </button>
                    </div>
                </div>

                <div v-else class="card">
                    <div class="card-body text-center text-secondary py-5">Select an email to start editing.</div>
                </div>
            </div>
        </div>
    </div>
</template>

<script setup>
import { computed, onMounted, ref } from 'vue';
import axios from 'axios';
import { confirmAdmin, notifyAdmin } from './adminAlerts';

const loading = ref(true);
const saving = ref(false);
const testing = ref(false);
const error = ref('');
const templates = ref([]);
const activeKey = ref('');
const form = ref({ subject: '', greeting: '', body: '', action_label: '', salutation: '' });
const testEmail = ref('');
const lastFocused = ref('tpl-body');

const active = computed(() => templates.value.find((t) => t.key === activeKey.value) || null);

const editableFields = computed(() => {
    if (!active.value) {
        return [];
    }
    const variables = active.value.variables;
    const fields = [
        { name: 'subject', label: 'Subject', type: 'text', default: active.value.defaults.subject, variables },
        { name: 'greeting', label: 'Greeting', type: 'text', default: active.value.defaults.greeting, variables },
        { name: 'body', label: 'Body (one line per row)', type: 'textarea', variables },
    ];

    if (active.value.defaults.action) {
        fields.push({ name: 'action_label', label: 'Button label', type: 'text', default: active.value.defaults.action.label, variables });
    }
    fields.push({ name: 'salutation', label: 'Closing line', type: 'text', default: active.value.defaults.salutation, variables });

    return fields;
});

const defaultBodyText = computed(() => (active.value ? active.value.defaults.lines.join('\n') : ''));

const senderLabel = computed(() => {
    const configured = document.querySelector('meta[name="mail-from"]');
    return configured?.content || 'Nexus Peptides | UAE Team';
});

/** Merge the form over the built-in defaults exactly like the server does, with sample values substituted. */
const livePreview = computed(() => {
    const fallback = active.value
        ? {
            subject: active.value.defaults.subject,
            greeting: active.value.defaults.greeting,
            body: active.value.defaults.lines.join('\n'),
            actionLabel: active.value.defaults.action ? active.value.defaults.action.label : '',
            salutation: active.value.defaults.salutation,
        }
        : { subject: '', greeting: '', body: '', actionLabel: '', salutation: '' };

    const merged = {
        subject: form.value.subject.trim() ? form.value.subject : fallback.subject,
        greeting: form.value.greeting.trim() ? form.value.greeting : fallback.greeting,
        body: form.value.body.trim() ? form.value.body : fallback.body,
        actionLabel: form.value.action_label.trim() ? form.value.action_label : fallback.actionLabel,
        salutation: form.value.salutation.trim() ? form.value.salutation : fallback.salutation,
    };

    const samples = Object.fromEntries((active.value?.variables || []).map((v) => [`{${v.name}}`, v.sample]));
    const substitute = (text) => text.replace(/\{\s*(\w+)\s*\}/g, (match, key) => samples[`{${key}}`] ?? match);

    return Object.fromEntries(Object.entries(merged).map(([key, value]) => [key, substitute(String(value ?? ''))]));
});

function isDirty(template) {
    return ['subject', 'greeting', 'body', 'action_label', 'salutation'].some(
        (field) => (form.value[field] || '') !== (template.fields[field] || '')
    ) && template.key === activeKey.value;
}

function loadForm(template) {
    form.value = {
        subject: template.fields.subject || '',
        greeting: template.fields.greeting || '',
        body: template.fields.body || '',
        action_label: template.fields.action_label || '',
        salutation: template.fields.salutation || '',
    };
}

function selectTemplate(key) {
    activeKey.value = key;
    loadForm(active.value);
}

function insertVariable(variable) {
    const target = lastFocused.value.replace('tpl-', '');
    if (!editableFields.value.some((field) => field.name === target)) {
        return;
    }
    form.value[target] = `${form.value[target]}{${variable.name}}`;
}

async function load() {
    loading.value = true;
    error.value = '';
    try {
        const { data } = await axios.get('/api/email-templates');
        templates.value = data.templates;
        if (!activeKey.value && templates.value.length) {
            selectTemplate(templates.value[0].key);
        }
    } catch (exception) {
        error.value = 'Email templates could not be loaded. Try again.';
    } finally {
        loading.value = false;
    }
}

function refreshFromResponse(payload) {
    const template = templates.value.find((t) => t.key === activeKey.value);
    if (!template) {
        return;
    }
    Object.assign(template, {
        overridden: payload.overridden ?? template.overridden,
        fields: payload.fields ?? template.fields,
        defaults: payload.defaults ?? template.defaults,
        preview: payload.preview ?? template.preview,
    });
    if (payload.fields) {
        loadForm(template);
    }
}

async function save() {
    saving.value = true;
    error.value = '';
    try {
        const { data } = await axios.put(`/api/email-templates/${activeKey.value}`, {
            subject: form.value.subject.trim() || null,
            greeting: form.value.greeting.trim() || null,
            body: form.value.body.trim() || null,
            action_label: form.value.action_label.trim() || null,
            salutation: form.value.salutation.trim() || null,
            is_active: true,
        });
        refreshFromResponse(data);
        notifyAdmin('success', data.message || 'Template saved.');
    } catch (exception) {
        const status = exception?.response?.status;
        if (status === 422) {
            const messages = Object.values(exception.response.data.errors ?? {}).flat();
            error.value = messages[0] || 'The template wording was rejected.';
        } else {
            error.value = 'The template could not be saved. Try again.';
        }
        notifyAdmin('error', error.value);
    } finally {
        saving.value = false;
    }
}

async function revert() {
    const result = await confirmAdmin({
        title: 'Revert to the built-in wording?',
        text: `Your custom wording for the ${active.value.label} is deleted and the built-in text goes live immediately.`,
        confirmButtonText: 'Revert',
        destructive: true,
    });
    if (!result.isConfirmed) {
        return;
    }

    saving.value = true;
    try {
        const { data } = await axios.delete(`/api/email-templates/${activeKey.value}`);
        refreshFromResponse(data);
        notifyAdmin('success', data.message || 'Reverted to the built-in wording.');
    } catch (exception) {
        error.value = 'The template could not be reverted. Try again.';
        notifyAdmin('error', error.value);
    } finally {
        saving.value = false;
    }
}

async function sendTest() {
    testing.value = true;
    error.value = '';
    try {
        const { data } = await axios.post(`/api/email-templates/${activeKey.value}/test`, { email: testEmail.value });
        notifyAdmin('success', data.message);
    } catch (exception) {
        error.value = exception?.response?.data?.message || 'The test email could not be sent. Check the mail settings.';
        notifyAdmin('error', error.value);
    } finally {
        testing.value = false;
    }
}

onMounted(load);
</script>

<style scoped>
.email-preview div {
    line-height: 1.6;
}

